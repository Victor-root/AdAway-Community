package org.adaway.root

import org.adaway.data.db.SourceEntity
import org.adaway.data.settings.Settings
import org.adaway.engine.Engine
import org.adaway.engine.EngineFiles
import java.io.File
import java.time.LocalDateTime
import java.time.format.DateTimeFormatter
import java.util.Locale

/** The hosts file generated for the root blocking, its header in English as the earlier versions wrote it. */
object HostsFile {
    /** The first line of every hosts file this app writes, followed by the date. */
    const val SIGNATURE = "# This hosts file has been generated by AdAway on: "

    /** The hosts file the apps read, readable without root. */
    val SYSTEM = File("/system/etc/hosts")

    /** What Android ships, put back when the device file was never saved. */
    const val ANDROID_DEFAULT = "127.0.0.1 localhost\n::1 ip6-localhost\n"

    private val DATE = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss", Locale.ROOT)

    /** Writes it from the final list. Throws a [RuntimeException] when it cannot be written. */
    fun write(files: EngineFiles, sources: List<SourceEntity>, labels: (SourceEntity) -> String, settings: Settings): File {
        val header = listOf(
            SIGNATURE + LocalDateTime.now().format(DATE),
            "# Please do not modify it directly, it will be overwritten when AdAway is applied again.",
            "# This file is generated from the following sources:",
        ) + sources.filter { it.enabled }.sortedBy { it.url }.map { "# - ${oneLine(labels(it))}:${oneLine(it.url)}" }
        files.rootDirectory.mkdirs()
        val output = File(files.rootDirectory, "hosts")
        Engine.writeHosts(
            finalDirectory = files.finalDirectory.path,
            output = output.path,
            header = header.toTypedArray(),
            ipv4Redirection = settings.rootRedirectionIpv4,
            ipv6Redirection = settings.rootRedirectionIpv6.takeIf { settings.ipv6Enabled },
        )
        return output
    }

    /** A text from the user kept on its comment line: a line break would add an active entry. */
    private fun oneLine(text: String) = text.filterNot { it.isISOControl() }
}
